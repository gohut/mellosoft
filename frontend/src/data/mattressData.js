export function getCalculatedPrice(productId, variantName, dimension) {
  const prod = MATTRESS_PRODUCTS.find((p) => p.id === productId || p.slug === productId) ||
               ACCESSORY_PRODUCTS.find((p) => p.id === productId || p.slug === productId);
  if (!prod || !prod.prices) return null;
  if (variantName && dimension && prod.prices[variantName] && prod.prices[variantName][dimension] !== undefined) {
    const val = prod.prices[variantName][dimension];
    return typeof val === "number" && val > 0 ? val : null;
  }
  return prod.startingPrice || null;
}
