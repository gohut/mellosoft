function generateMattressMatrix(basePrice, thicknesses = ["4 inch", "5 inch"]) {
  const dims = [
    "72 x 30", "72 x 36", "75 x 30", "75 x 36", "78 x 30", "78 x 36", "84 x 36",
    "72 x 42", "72 x 44", "72 x 48", "75 x 44", "75 x 48", "78 x 48", "84 x 48",
    "72 x 60", "75 x 60", "78 x 60", "84 x 60",
    "72 x 72", "75 x 72", "78 x 72", "84 x 72"
  ];
  const prices = {};
  thicknesses.forEach((t, tIdx) => {
    prices[t] = {};
    const tMult = 1 + tIdx * 0.25;
    dims.forEach((d) => {
      const [w, h] = d.split(" x ").map(Number);
      const ratio = (w * h) / (72 * 30);
      prices[t][d] = Math.round(basePrice * tMult * ratio);
    });
  });
  return prices;
}

